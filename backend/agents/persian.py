def _exact_replace(text: str) -> str:
    """Apply the exact-word dictionary with Persian word boundaries.

    ZWNJ is treated as part of the word (not a boundary), so an already-fixed
    compound like حل\u200cنشده is never re-matched and re-split.
    """
    # Boundary: anything that is not a Persian letter and not ZWNJ.
    pattern = re.compile(
        r"(?<![\u0600-\u06FF\u200c])(%s)(?![\u0600-\u06FF\u200c])"
        % "|".join(re.escape(w) for w in sorted(_ZWNJ_WORDS, key=len, reverse=True))
    )
    return pattern.sub(lambda m: _ZWNJ_WORDS[m.group(1)], text)


# ---------------------------------------------------------------------------
# Regex rules — conservative, exclusion-guarded.
# ---------------------------------------------------------------------------
_PERSIAN_LETTER = r"[\u0600-\u06FF]"

# ه + ی at word end: جلسهی -> جلسه\u200cی. Exclusions are real single words.
_H_Y_EXCLUDE = {
    "ماهی", "شاهی", "راهی", "هی", "مهی", "بهی", "ناهی", "چاهی",
    "آهی", "تاهی", "پیهی", "فهمی", "تهمی", "جامی", "آبی", "تهی",
}

# ها / های / هایی plural suffix. Exclusions are roots that end in ها.
_HA_EXCLUDE = {
    "رها", "بها", "دها", "تها", "ناها", "چاها", "پناه", "نگاه", "گاه",
    "آگاه", "شاه", "چاه", "ماه", "گیاه", "سیاه",
}

# می + verb prefix. Exclusions are common می-words that are NOT می+verb.
_MI_EXCLUDE = {
    "میز", "میوه", "میدان", "میزان", "میل", "میخ", "میله", "میهن",
    "میلیون", "میانه", "میان", "میعاد", "میثاق", "میراث", "میمون",
    "میکرو", "میخک", "میلاد", "میدانی", "میخچه", "میگ", "میگسار",
    "میخانه", "میخواره", "میرزا", "میترا", "میکس", "میانگین", "میانبر",
    "میهمان", "میهمانی",
}


def _fix_zwnj_rules(text: str) -> str:
    """Insert ZWNJ for the three high-frequency patterns, exclusion-guarded."""

    def _apply(pattern: re.Pattern, text: str, exclude: set[str]) -> str:
        def _sub(m: re.Match) -> str:
            word = m.group(0)
            if word in exclude:
                return word
            return m.group(1) + ZWNJ + m.group(2)

        return pattern.sub(_sub, text)

    # 1) ه + ی attributive at word end: جلسهی -> جلسه\u200cی
    text = _apply(
        re.compile(r"(?<![\u0600-\u06FF])(" + _PERSIAN_LETTER + r"+ه)(ی)(?![\u0600-\u06FF])"),
        text,
        _H_Y_EXCLUDE,
    )
    # 2) plural ها/های/هایی: مشتریها -> مشتری\u200cها
    text = _apply(
        re.compile(r"(?<![\u0600-\u06FF])(" + _PERSIAN_LETTER + r"+)(ها)(?![\u0600-\u06FF])"),
        text,
        _HA_EXCLUDE,
    )
    # 3) می + verb prefix at word start: میشود -> می\u200cشود
    text = _apply(
        re.compile(r"(?<![\u0600-\u06FF])(می)(" + _PERSIAN_LETTER + r"{2,})(?![\u0600-\u06FF])"),
        text,
        _MI_EXCLUDE,
    )
    return text


def fix_persian_zwnj(text: str) -> str:
    """Restore نیمفاصله (ZWNJ) in Persian text.

    Exact-word dictionary first (safe), then conservative regex rules. Only
    inserts ZWNJ; never removes or reorders anything. Non-Persian text passes
    through untouched.
    """
    if not text:
        return text
    if not any("\u0600" <= ch <= "\u06FF" for ch in text):
        return text
    out = _exact_replace(text)
    out = _fix_zwnj_rules(out)
    return out
